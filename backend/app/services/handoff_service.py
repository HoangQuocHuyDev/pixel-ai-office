import re
from typing import Any

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.agents.registry import default_agent_registry
from app.core.exceptions import ApplicationError
from app.models.agent_handoff import AgentHandoff
from app.models.artifact import Artifact
from app.models.task import Task
from app.models.task_execution import TaskExecution

MAX_SUMMARY_CHARS = 500
MAX_FINDINGS_COUNT = 6
MAX_FINDING_CHARS = 200
MAX_NEXT_STEPS_CHARS = 500


def _agent_display_name(agent_id: str | None) -> str:
    if not agent_id:
        return "Unknown Agent"
    try:
        return default_agent_registry.get(agent_id).name
    except ApplicationError:
        return agent_id.capitalize()


def extract_handoff_content(
    output_content: str,
    source_task: Task,
    target_task: Task,
    artifacts: list[Artifact],
) -> dict[str, Any]:
    clean_output = output_content.strip()

    # Extract summary
    paragraphs = [p.strip() for p in clean_output.split("\n\n") if p.strip()]
    first_paragraph = paragraphs[0] if paragraphs else clean_output
    # Remove leading markdown headers if any (e.g. # Title)
    first_paragraph = re.sub(r"^#+\s*", "", first_paragraph).strip()
    summary = first_paragraph[:MAX_SUMMARY_CHARS]
    if len(first_paragraph) > MAX_SUMMARY_CHARS:
        summary = summary.rsplit(" ", 1)[0] + "..."

    # Extract bullet point key findings
    raw_lines = clean_output.splitlines()
    bullet_items: list[str] = []
    for line in raw_lines:
        trimmed = line.strip()
        match = re.match(r"^[-*•]\s+(.*)$", trimmed) or re.match(r"^\d+\.\s+(.*)$", trimmed)
        if match:
            item = match.group(1).strip()
            # Ignore headers or short artifacts markers
            if len(item) >= 5:
                truncated = item[:MAX_FINDING_CHARS]
                bullet_items.append(truncated)
                if len(bullet_items) >= MAX_FINDINGS_COUNT:
                    break

    # If no bullet points found, extract 1-2 key sentences from subsequent paragraphs
    if not bullet_items and len(paragraphs) > 1:
        for p in paragraphs[1:3]:
            sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", p) if len(s.strip()) >= 15]
            for s in sentences:
                bullet_items.append(s[:MAX_FINDING_CHARS])
                if len(bullet_items) >= 3:
                    break
            if len(bullet_items) >= 3:
                break

    # Extract deliverables from actual artifacts or task output
    deliverables: list[str] = []
    if artifacts:
        deliverables = [artifact.title[:150] for artifact in artifacts]
    else:
        deliverables = [f"Output document for {source_task.title}"[:150]]

    # Next steps instruction for target task
    target_desc = f": {target_task.description}" if target_task.description else ""
    next_steps = f"Proceed with {target_task.title}{target_desc}"[:MAX_NEXT_STEPS_CHARS]

    return {
        "summary": summary or f"Completed {source_task.title}.",
        "key_findings": bullet_items,
        "deliverables": deliverables,
        "next_steps": next_steps,
        "artifact_ids": [a.id for a in artifacts],
    }


def create_agent_handoff(
    db: Session,
    workflow_run_id: int,
    source_execution_id: int,
    source_task: Task,
    target_task: Task,
) -> AgentHandoff | None:
    if source_task.id == target_task.id:
        return None
    if source_task.plan_id is not None and target_task.plan_id is not None and source_task.plan_id != target_task.plan_id:
        return None

    execution = db.get(TaskExecution, source_execution_id)
    if execution is None or execution.status != "completed" or not execution.output_content:
        return None
    if execution.workflow_run_id is None or execution.workflow_run_id != workflow_run_id:
        return None

    # Idempotency check: don't create duplicate handoff if already present
    existing = db.scalar(
        select(AgentHandoff).where(
            AgentHandoff.source_task_execution_id == source_execution_id,
            AgentHandoff.target_task_id == target_task.id,
        )
    )
    if existing is not None:
        return existing

    # Find verified artifacts generated by this execution
    artifacts = list(
        db.scalars(
            select(Artifact)
            .where(Artifact.task_execution_id == source_execution_id)
            .order_by(Artifact.id.asc())
        ).all()
    )

    data = extract_handoff_content(
        execution.output_content,
        source_task,
        target_task,
        artifacts,
    )

    handoff = AgentHandoff(
        workflow_run_id=workflow_run_id,
        source_task_execution_id=source_execution_id,
        source_agent_id=execution.agent_id,
        target_task_id=target_task.id,
        target_agent_id=target_task.assigned_agent_id or "developer",
        summary=data["summary"],
        key_findings=data["key_findings"],
        deliverables=data["deliverables"],
        next_steps=data["next_steps"],
        artifact_ids=data["artifact_ids"],
    )
    try:
        with db.begin_nested():
            db.add(handoff)
            db.flush()
        return handoff
    except IntegrityError:
        return db.scalar(
            select(AgentHandoff).where(
                AgentHandoff.source_task_execution_id == source_execution_id,
                AgentHandoff.target_task_id == target_task.id,
            )
        )


def format_handoff_for_context(
    handoff: AgentHandoff,
    source_task_title: str,
) -> str:
    source_name = _agent_display_name(handoff.source_agent_id)
    target_name = _agent_display_name(handoff.target_agent_id)
    lines = [
        f"Structured Handoff from {source_name} to {target_name} (Source: '{source_task_title}'):",
        f"Summary: {handoff.summary}",
    ]
    if handoff.key_findings:
        lines.append("Key findings:")
        for item in handoff.key_findings:
            lines.append(f"  • {item}")
    if handoff.deliverables:
        lines.append("Deliverables produced:")
        for d in handoff.deliverables:
            lines.append(f"  • {d}")
    if handoff.next_steps:
        lines.append(f"Next steps for this task: {handoff.next_steps}")
    return "\n".join(lines)

