MAX_ARTIFACT_CHARS = 1_000_000
CODE_MARKERS = ("```", "def ", "class ", "function ", "const ", "import ", "export ", "</", "SELECT ")


def _classify(agent_id: str, content: str) -> tuple[str, str, str | None]:
    stripped = content.strip()
    if agent_id == "researcher":
        return "research", "markdown" if "#" in stripped or "**" in stripped else "plain_text", None
    try:
        json.loads(stripped)
        return "document", "json", "json"
    except (json.JSONDecodeError, TypeError):
        pass
    if agent_id == "developer" and any(marker in stripped for marker in CODE_MARKERS):
        language_match = re.search(r"```([a-zA-Z0-9_+-]+)", stripped)
        return "code", "code", language_match.group(1).lower()[:50] if language_match else None
    return "document", "markdown" if "#" in stripped or "**" in stripped else "plain_text", None


def create_execution_artifact(db: Session, execution: TaskExecution, task: Task) -> Artifact | None:
    if execution.status != "completed" or not execution.output_content:
        return None
    existing = db.scalar(select(Artifact).where(Artifact.task_execution_id == execution.id))
    if existing is not None:
        return existing
    content = execution.output_content.strip()
    if not content or len(content) > MAX_ARTIFACT_CHARS:
        raise ApplicationError(422, "ARTIFACT_CONTENT_INVALID", "Artifact content must contain between 1 and 1,000,000 characters.")
    artifact_type, content_format, language = _classify(execution.agent_id, content)
    artifact = Artifact(
        title=f"{task.title} — Result"[:255], artifact_type=artifact_type, content=content,
        content_format=content_format, language=language, agent_id=execution.agent_id,
        task_id=task.id, task_execution_id=execution.id,
    )
    try:
        with db.begin_nested():
            db.add(artifact)
            db.flush()
            db.add(ArtifactVersion(
                artifact_id=artifact.id, version_number=1, content=content, content_format=content_format,
                language=language, source="agent", change_summary="Original version generated by the assigned agent.",
            ))
            db.flush()
        return artifact
    except IntegrityError:
        return db.scalar(select(Artifact).where(Artifact.task_execution_id == execution.id))


def create_workflow_artifact(db: Session, workflow: WorkflowRun, plan: Plan) -> Artifact | None:
    if workflow.status != "completed" or not workflow.final_report:
        return None
    existing = db.scalar(select(Artifact).where(Artifact.workflow_run_id == workflow.id))
    if existing is not None:
        return existing
    content = workflow.final_report.strip()
    if not content or len(content) > MAX_ARTIFACT_CHARS:
        raise ApplicationError(422, "ARTIFACT_CONTENT_INVALID", "Artifact content must contain between 1 and 1,000,000 characters.")
    artifact = Artifact(
        title=f"{plan.title} — Final Report"[:255], artifact_type="report", content=content,
        content_format="markdown" if "#" in content or "**" in content else "plain_text",
        agent_id="manager", workflow_run_id=workflow.id,
    )
    try:
        with db.begin_nested():
            db.add(artifact)
            db.flush()
            db.add(ArtifactVersion(
                artifact_id=artifact.id, version_number=1, content=content,
                content_format=artifact.content_format, language=None, source="agent",
                change_summary="Original final report generated by Manager AI.",
            ))
            db.flush()
        return artifact
    except IntegrityError:
        return db.scalar(select(Artifact).where(Artifact.workflow_run_id == workflow.id))


def backfill_artifacts(
    db: Session,
    *,
    execution_ids: set[int] | None = None,
    workflow_ids: set[int] | None = None,
) -> tuple[int, int]:
    execution_count = 0
    execution_statement = (
        select(TaskExecution, Task).join(Task, Task.id == TaskExecution.task_id)
        .outerjoin(Artifact, Artifact.task_execution_id == TaskExecution.id)
        .where(TaskExecution.status == "completed", TaskExecution.output_content.is_not(None), Artifact.id.is_(None))
    )
    if execution_ids is not None:
        execution_statement = execution_statement.where(TaskExecution.id.in_(execution_ids))
    rows = db.execute(execution_statement).all()
    for execution, task in rows:
        if create_execution_artifact(db, execution, task): execution_count += 1
    report_count = 0
    workflow_statement = (
        select(WorkflowRun, Plan).join(Plan, Plan.id == WorkflowRun.plan_id)
        .outerjoin(Artifact, Artifact.workflow_run_id == WorkflowRun.id)
        .where(WorkflowRun.status == "completed", WorkflowRun.final_report.is_not(None), Artifact.id.is_(None))
    )
    if workflow_ids is not None:
        workflow_statement = workflow_statement.where(WorkflowRun.id.in_(workflow_ids))
    workflows = db.execute(workflow_statement).all()
    for workflow, plan in workflows:
        if create_workflow_artifact(db, workflow, plan): report_count += 1
    db.flush()
    return execution_count, report_count


def _item(artifact: Artifact, task_title: str | None, workflow_title: str | None) -> ArtifactListItem:
    try:
        agent_name = default_agent_registry.get(artifact.agent_id).name if artifact.agent_id else None
    except ApplicationError:
        agent_name = artifact.agent_id
    return ArtifactListItem(
        id=artifact.id, title=artifact.title, artifact_type=artifact.artifact_type,
        content_format=artifact.content_format, language=artifact.language, agent_id=artifact.agent_id,
        agent_name=agent_name, task_id=artifact.task_id, task_title=task_title,
        workflow_run_id=artifact.workflow_run_id, workflow_title=workflow_title,
        created_at=artifact.created_at, preview=artifact.content[:240], content_size=len(artifact.content),
        current_version_number=artifact.current_version_number,
    )


def list_artifacts(db: Session, *, limit: int, offset: int, search: str | None = None, artifact_type: str | None = None, agent_id: str | None = None, task_id: int | None = None, workflow_run_id: int | None = None) -> ArtifactListResponse:
    statement = select(Artifact, Task.title, Plan.title).outerjoin(Task, Task.id == Artifact.task_id).outerjoin(WorkflowRun, WorkflowRun.id == Artifact.workflow_run_id).outerjoin(Plan, Plan.id == WorkflowRun.plan_id)
    count_statement = select(func.count(Artifact.id))
    conditions = []
    if search: conditions.append(Artifact.title.contains(search.strip(), autoescape=True))
    if artifact_type: conditions.append(Artifact.artifact_type == artifact_type)
    if agent_id: conditions.append(Artifact.agent_id == agent_id)
    if task_id is not None: conditions.append(Artifact.task_id == task_id)
    if workflow_run_id is not None: conditions.append(Artifact.workflow_run_id == workflow_run_id)
    if conditions:
        statement = statement.where(*conditions); count_statement = count_statement.where(*conditions)
    total = db.scalar(count_statement) or 0
    rows = db.execute(statement.order_by(Artifact.created_at.desc(), Artifact.id.desc()).offset(offset).limit(limit)).all()
    return ArtifactListResponse(items=[_item(artifact, task_title, workflow_title) for artifact, task_title, workflow_title in rows], total=total, limit=limit, offset=offset)


def get_artifact(db: Session, artifact_id: int) -> ArtifactDetail:
    row = db.execute(select(Artifact, Task.title, Plan.title).outerjoin(Task, Task.id == Artifact.task_id).outerjoin(WorkflowRun, WorkflowRun.id == Artifact.workflow_run_id).outerjoin(Plan, Plan.id == WorkflowRun.plan_id).where(Artifact.id == artifact_id)).one_or_none()
    if row is None: raise ApplicationError(404, "ARTIFACT_NOT_FOUND", f"Artifact {artifact_id} not found.")
    artifact, task_title, workflow_title = row
    return ArtifactDetail(**_item(artifact, task_title, workflow_title).model_dump(), task_execution_id=artifact.task_execution_id, content=artifact.content, updated_at=artifact.updated_at)


def artifact_summary(db: Session) -> ArtifactSummary:
    row = db.execute(select(
        func.count(Artifact.id),
        func.count(Artifact.id).filter(Artifact.artifact_type == "document"),
        func.count(Artifact.id).filter(Artifact.artifact_type == "code"),
        func.count(Artifact.id).filter(Artifact.artifact_type == "research"),
        func.count(Artifact.id).filter(Artifact.artifact_type == "report"),
    )).one()
    return ArtifactSummary(total_artifacts=row[0], documents=row[1], code=row[2], research=row[3], reports=row[4])
